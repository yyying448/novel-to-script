# 章节转换提示词
# ============================================================
CONVERT_CHAPTER_PROMPT = """请将以下小说章节内容改编为剧本 YAML 格式。

{character_profiles}
=== 小说原文 ===
{chapter_text}
===

请严格按照以下 YAML 结构输出（不要输出 ``` 标记之外的其他内容）：

```yaml
scenes:
  - scene_id: <从1开始的数字>
    location: "<内景/外景> - <具体地点> - <时间(如:日/夜/黄昏/清晨)>"
    characters_present:
      - name: "<角色名称>"
        role: "<主角/重要配角/配角/龙套>"
    summary: "<本场景一句话概括，20字以内>"
    dialogues:
      - speaker: "<说话人名称>"
        lines:
          - "<第一句台词>"
          - "<第二句台词>（如有多句分行写）"
        tone: "<语气描述，如:平静但坚定/愤怒/温柔/讽刺>"
        action: "<说话同时进行的动作描述>"
    scene_notes: "<编剧备注：本场景的戏剧功能、情绪基调、与其他场景的关联>"
```

注意：
- 每个 scene 只包含一个连续时空内的剧情
- 如果一个场景中同一人连续说多句话，放在同一个 dialogue 的 lines 数组中
- 对话要口语化——想想演员怎么念出来自然
- action 描述人物当下的动作、表情、走位
- 从小说描写中合理推断 tone（语气），不要每句都写"平静"
- scene_notes 要写清楚这场戏在整体剧情中的作用（建立人物/推进剧情/埋下伏笔/制造冲突等）
- 场景数量不做限制，忠实反映原著内容即可"""


